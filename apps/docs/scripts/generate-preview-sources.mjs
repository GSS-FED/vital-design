// Extracts each exported function from apps/docs/components/previews/*.tsx
// into a single source map at apps/docs/components/previews/__sources__.ts.
// The Code tab in <ComponentPreview /> reads from this map.
//
// We also pre-bake Shiki highlighting at generation time so the runtime
// doesn't have to do server-side highlighting per page — keeps
// ComponentPreview as a client component (preview files use 'use client').
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { codeToHtml } from 'shiki';

const __dirname = dirname(fileURLToPath(import.meta.url));
const previewsDir = join(__dirname, '..', 'components', 'previews');
const outFile = join(previewsDir, '__sources__.ts');

const files = readdirSync(previewsDir).filter(
  (f) => f.endsWith('.tsx') && !f.startsWith('_'),
);

const sources = {};

for (const file of files) {
  const raw = readFileSync(join(previewsDir, file), 'utf-8');

  // Imports: keep everything but the ComponentPreview import.
  const importLines = (
    raw.match(/^import[\s\S]*?from\s+['"][^'"]+['"];?\s*$/gm) ?? []
  )
    .filter(
      (line) => !/components\/preview\/ComponentPreview/.test(line),
    )
    .map((line) => line.trim());

  // Each exported function block: `export function Name(...) { ... }`
  const fnRegex =
    /export\s+function\s+(\w+Preview)\s*\([^)]*\)\s*\{([\s\S]*?)\n\}/g;
  let match;
  while ((match = fnRegex.exec(raw)) !== null) {
    const fnName = match[1];
    let body = match[2];

    // Strip the <ComponentPreview ...>...</ComponentPreview> wrapper but keep
    // the children. This leaves the demo as the user would actually write it.
    body = body
      .replace(/<ComponentPreview\b[^>]*>\s*/g, '')
      .replace(/\s*<\/ComponentPreview>/g, '');

    // Reassemble import block + the function shorn of its preview wrapper.
    const code = [
      importLines.join('\n'),
      '',
      `export function ${fnName}() {${body}\n}`,
    ]
      .filter((segment) => segment.length > 0 || segment === '')
      .join('\n');

    sources[fnName] = code;
  }
}

const sortedKeys = Object.keys(sources).sort();

// Pre-highlight each source with shiki so ComponentPreview doesn't have to
// at runtime. Strip Shiki's own background — the docs container sets it.
const entries = await Promise.all(
  sortedKeys.map(async (name) => {
    const code = sources[name];
    let html = await codeToHtml(code, {
      lang: 'tsx',
      theme: 'github-light',
    });
    html = html.replace(
      /style="background-color:[^"]+;color:/,
      'style="color:',
    );
    return [name, { source: code, html }];
  }),
);

const banner = `// Auto-generated by scripts/generate-preview-sources.mjs.\n// Run \`pnpm previews:sources\` to regenerate.\n\n`;
const body =
  'export type PreviewSource = { source: string; html: string };\n\n' +
  'export const previewSources: Record<string, PreviewSource> = {\n' +
  entries
    .map(
      ([name, value]) =>
        `  ${JSON.stringify(name)}: {\n    source: ${JSON.stringify(
          value.source,
        )},\n    html: ${JSON.stringify(value.html)},\n  },`,
    )
    .join('\n') +
  '\n};\n';

writeFileSync(outFile, banner + body);

console.log(
  `Generated ${sortedKeys.length} preview sources into ${outFile}`,
);
